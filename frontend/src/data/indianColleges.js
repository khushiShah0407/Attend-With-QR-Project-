export const getAllIndianColleges = () => {
  const customColleges = loadStoredData(STORAGE_KEY_CUSTOM_COLLEGES, []);
  return [...customColleges, ...POPULAR_INDIAN_COLLEGES];
};

export const registerCustomCollege = ({ name, city, state, code, departments }) => {
  const customList = loadStoredData(STORAGE_KEY_CUSTOM_COLLEGES, []);
  const newCollege = {
    id: `custom-clg-${Date.now()}`,
    name: name.trim(),
    city: city ? city.trim() : 'India',
    state: state ? state.trim() : 'India',
    code: code ? code.trim().toUpperCase() : name.slice(0, 4).toUpperCase(),
    departments:
      departments && departments.length > 0 ? departments : STANDARD_DEPARTMENTS.slice(0, 5),
    isCustom: true,
  };

  const updated = [newCollege, ...customList];
  saveStoredData(STORAGE_KEY_CUSTOM_COLLEGES, updated);
  return newCollege;
};
